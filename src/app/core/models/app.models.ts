export interface Customer {
  id?: string; // Optional because ID is generated by Firestore
  name: string;
  email: string; // Added: Will be required and validated
  address?: string;
  gst?: string; // Existing, will add validation pattern
  phone?: string; // Added: Optional, will add validation pattern
  contact?: string; // Existing: General contact person/details, distinct from validated phone
}

export interface InvoiceItem {
  description: string;
  amount: number;
}

export interface Invoice {
  id?: string; // Optional because ID is generated by Firestore
  customer: string | Customer; // Could be customer ID or a populated customer object
  customerId?: string; // Store ID explicitly if customer is an object
  clientManager: string;
  items: InvoiceItem[];
  logo?: string; // This might be deprecated if only default logo is used
  subtotal: number;
  gst: number;
  total: number;
  amountInWords: string;
  invoiceNumber?: string; // Usually generated or assigned
  date?: Date | string; // Or a Firestore Timestamp

  // Fields for Payment Tracking
  paymentStatus: 'Unpaid' | 'Partially Paid' | 'Paid' | 'Overdue';
  totalPaid: number;
  dueDate?: Date | string;
}

export interface Payment {
  id?: string; // Firestore generated ID
  invoiceId: string; // Foreign key to Invoice
  paymentDate: Date | string; // Date of payment
  amountPaid: number;
  paymentMethod?: 'Cash' | 'Credit Card' | 'Bank Transfer' | 'Cheque' | 'Other';
  notes?: string;
}
